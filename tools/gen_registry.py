"""Write the native function tables for builds without recompiled code (gen/).

Every `entry` row in config/splices/*.txt is a handwritten routine that replaces a whole
original routine. Interpreter builds call it through the dispatcher like recompiled code,
and interpret the original instructions whenever it declines (returns false), exactly as
the recompiled function would fall back to its translated instructions.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = (
    "slus_005_82",
    "psx_exe",
    "psx2_exe",
    "credits_exe",
    "stream1_exe",
    "stream2_exe",
    "stream3_exe",
)


def load(splices: Path):
    """Return {module: {addr: call}} and the headers those calls need."""
    entries = {m: {} for m in MODULES}
    headers = []
    for path in sorted(splices.glob("*.txt")):
        includes, used = [], False
        for number, line in enumerate(path.read_text().splitlines(), 1):
            text = line.split("#", 1)[0].strip()
            if not text:
                continue
            fields = text.split(None, 3)
            if fields[0] == "include" and len(fields) == 2:
                includes.append(fields[1])
                continue
            where = f"{path.name}, line {number}"
            if len(fields) != 4 or fields[2] not in ("entry", "at"):
                raise ValueError(f"{where}: expected '<module> <addr> entry|at <code>'")
            if fields[0] not in entries:
                raise ValueError(f"{where}: unknown module {fields[0]}")
            addr = int(fields[1], 16)
            if addr % 4:
                raise ValueError(f"{where}: misaligned address")
            if fields[2] != "entry":
                continue
            if addr in entries[fields[0]]:
                raise ValueError(f"{where}: second entry for {fields[0]} {addr:08X}")
            entries[fields[0]][addr] = fields[3]
            used = True
        if used:
            headers.extend(h for h in includes if h not in headers)
    return entries, headers


def render(entries, headers) -> str:
    lines = [
        "/* Generated by tools/gen_registry.py from config/splices. Do not edit. */",
        '#include "port/interp.h"',
        '#include "port/recomp.h"',
        '#include "port/shadow.h"',
        *(f'#include "{h}"' for h in headers),
        "",
    ]
    for module in MODULES:
        for addr, call in sorted(entries[module].items()):
            name = f"{module}_{addr:08X}"
            text = call.replace("\\", "\\\\").replace('"', '\\"')
            lines += [
                f"static bool {name}_native(CPUState *c) {{",
                f"    return {call};",
                "}",
                f"static void {name}(CPUState *c) {{",
                "    if (nc_shadow_enabled &&",
                f'        nc_shadow_call(c, 0x{addr:08X}u, "{text}", {name}_native))',
                "        return;",
                f"    if (!({call}))",
                f"        interp_call(c, 0x{addr:08X}u);",
                "}",
            ]
        lines.append("")
    for module in MODULES:
        rows = sorted(entries[module])
        if rows:
            lines.append(f"const NcFuncEntry {module}_table[] = {{")
            lines += [f"    {{0x{a:08X}u, {module}_{a:08X}}}," for a in rows]
            lines.append("};")
        else:
            lines.append(f"const NcFuncEntry {module}_table[1];")
        lines.append(f"const unsigned {module}_table_len = {len(rows)};")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("out", type=Path)
    ap.add_argument("--splices", type=Path, default=ROOT / "config" / "splices")
    args = ap.parse_args()
    text = render(*load(args.splices))
    if not args.out.exists() or args.out.read_text() != text:
        args.out.write_text(text)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError) as exc:
        sys.exit(str(exc))
