"""Port handwritten CREDITS.EXE routines to their identical twins in the other executables.

Many routines (mostly Psy-Q library code) appear instruction for instruction in several
executables, differing only in the addresses they use. A handwritten routine for one copy
therefore becomes a routine for another by translating every address it uses.

  --discover   (needs build/splat) pairs each fully covered CREDITS.EXE function with its
               uncovered twins and records the address translation for each target module
               in config/twins/<module>.txt: unit pairs, and every address the two
               instruction streams relate (jal targets, %hi/%lo pairs, code inside the unit).
  (default)    regenerates the ported C (src/decomp/twins/), its splice rows
               (config/splices/twins_<module>.txt) and coverage ranges from those files.
  --check      fails if the generated files are out of date (CI runs this; no disc needed).

A routine is ported only when every address literal in its code (and in the code it
depends on) has a translation, so nothing is guessed. Ported routines are checked against
the interpreter on real game states by `make shadow`.
"""

import argparse
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = "credits_exe"
TARGETS = ("psx_exe", "psx2_exe", "stream1_exe", "stream2_exe", "stream3_exe")
LAUNCHER_LO, OVERLAY_LO, RAM_HI = 0x80010000, 0x80018000, 0x80200000
TWINS = ROOT / "config" / "twins"
SPLICES = ROOT / "config" / "splices"
OUT = ROOT / "src" / "decomp" / "twins"
RANGES = ROOT / "config" / "decomp_ranges.txt"
RANGES_MARK = "# --- Ported twins: generated by tools/port_twins.py, do not edit below ---"
LITERAL = re.compile(r"\b0x([0-9a-fA-F]{8})(u?)\b")
IDENT = re.compile(r"\b[A-Za-z_]\w*\b")


# --- discovery (needs the disassembly) ------------------------------------------------------


def relocations(a, b, amap, himap):
    """Record the addresses that twin units a and b relate, instruction by instruction."""
    hi_a, hi_b = {}, {}
    for ea, eb in zip(a.entries, b.entries, strict=True):
        wa, wb = ea.word, eb.word
        op = wa >> 26
        rt, rs = (wa >> 16) & 31, (wa >> 21) & 31
        if op in (2, 3):
            ta = (ea.address & 0xF0000000) | (wa & 0x03FFFFFF) << 2
            tb = (eb.address & 0xF0000000) | (wb & 0x03FFFFFF) << 2
            amap[ta].add(tb)
        elif op == 0x0F:  # lui
            hi_a[rt], hi_b[rt] = (wa & 0xFFFF) << 16, (wb & 0xFFFF) << 16
            himap[hi_a[rt]].add(hi_b[rt])
        elif op >= 8 and rs in hi_a and (op in (9, 13) or op >= 0x20):
            lo_a, lo_b = wa & 0xFFFF, wb & 0xFFFF
            if op == 13:  # ori: zero-extended
                full_a, full_b = hi_a[rs] | lo_a, hi_b[rs] | lo_b
            else:
                full_a = (hi_a[rs] + ((lo_a ^ 0x8000) - 0x8000)) & 0xFFFFFFFF
                full_b = (hi_b[rs] + ((lo_b ^ 0x8000) - 0x8000)) & 0xFFFFFFFF
            amap[full_a].add(full_b)
        # Any other write to a register ends the %hi value it held.
        dest = None
        if op == 0:
            dest = (wa >> 11) & 31
        elif 8 <= op <= 0x0E or 0x20 <= op <= 0x26:
            dest = rt
        elif op == 3:
            dest = 31
        if dest is not None:
            hi_a.pop(dest, None)
            hi_b.pop(dest, None)
    for k in range(0, a.end - a.start, 4):
        amap[a.start + k].add(b.start + k)
    amap[a.end].add(b.end)


def constants_differ(a, b):
    """True if the units differ anywhere but in addresses: the twin hash masks every lui
    value, so two routines differing only in a lui constant hash alike."""
    for ea, eb in zip(a.entries, b.entries, strict=True):
        if ea.word == eb.word:
            continue
        op = ea.word >> 26
        if op in (2, 3):
            continue  # jump targets
        if op == 0x0F:
            hi_a, hi_b = ea.word & 0xFFFF, eb.word & 0xFFFF
            if not (0x8001 <= hi_a < 0x8020 and 0x8001 <= hi_b < 0x8020):
                return True
            continue
        if ea.word & 0xFFFF0000 != eb.word & 0xFFFF0000:
            return True  # only the 16-bit immediate of a %lo or $gp use may differ
    return False


def gp_differs(a, b):
    for ea, eb in zip(a.entries, b.entries, strict=True):
        op = ea.word >> 26
        if op >= 4 and op not in (0x10, 0x11, 0x12, 0x13) and (ea.word >> 21) & 31 == 28:
            if ea.word != eb.word:
                return True
    return False


def discover():
    import decomp_state as state
    import work_queue as wq

    state.require_asm()
    modules = state.inventory("asm")
    covered, _ = state.coverage(modules)
    ranges_src = ranges_sources()
    hashes = defaultdict(list)
    for stem, module in modules.items():
        for unit in module.units:
            if digest := wq.body_hash(unit):
                hashes[digest].append((stem, unit))
    TWINS.mkdir(parents=True, exist_ok=True)
    for target in TARGETS:
        pairs, amap, himap = [], defaultdict(set), defaultdict(set)
        claimed = set()
        for unit in modules[SOURCE].units:
            if wq.status_of(unit, covered[SOURCE])[0] != "covered":
                continue
            # Coverage credited only to the ports themselves does not count as a source.
            if any(ranges_src.get((SOURCE, a), "").startswith("twins/") for a in unit.counted):
                continue
            for stem, twin in hashes.get(wq.body_hash(unit), []):
                if stem != target or twin.start in claimed:
                    continue
                if len(twin.entries) != len(unit.entries) or gp_differs(unit, twin):
                    continue
                if constants_differ(unit, twin):
                    continue
                if any(
                    ranges_src.get((target, a), "twins/").split("/")[0] != "twins"
                    for a in twin.counted
                    if a in covered[target]
                ):
                    continue  # already handwritten for this module
                claimed.add(twin.start)
                local_map, local_hi = defaultdict(set), defaultdict(set)
                relocations(unit, twin, local_map, local_hi)
                for k, v in local_map.items():
                    amap[k] |= v
                for k, v in local_hi.items():
                    himap[k] |= v
                pairs.append((unit, twin, local_map, local_hi))
        lines = [
            f"# Twins of handwritten {SOURCE} functions in {target}.",
            "# Written by tools/port_twins.py --discover.",
            "# unit <source start> <source end> <target start> [counted runs in the target]",
            "# map <source address> <target address>   (only unambiguous translations)",
            "# hi <source %hi value> <target %hi value>   (the same everywhere)",
            "# umap, uhi: the same, within the unit above only",
            "",
        ]
        for unit, twin, local_map, local_hi in sorted(pairs, key=lambda p: p[1].start):
            runs = " ".join(f"{s:08X}-{e:08X}" for s, e in state.runs(twin.counted))
            lines.append(f"unit {unit.start:08X} {unit.end:08X} {twin.start:08X} {runs}")
            # Only what the global map below does not already say.
            for k in sorted(local_map):
                if len(local_map[k]) == 1 and len(amap[k]) != 1:
                    lines.append(f"umap {k:08X} {next(iter(local_map[k])):08X}")
            for k in sorted(local_hi):
                if len(local_hi[k]) == 1 and len(himap[k]) != 1:
                    lines.append(f"uhi {k:08X} {next(iter(local_hi[k])):08X}")
        for addr in sorted(amap):
            if len(amap[addr]) == 1:
                lines.append(f"map {addr:08X} {next(iter(amap[addr])):08X}")
        for addr in sorted(himap):
            if len(himap[addr]) == 1:
                lines.append(f"hi {addr:08X} {next(iter(himap[addr])):08X}")
        (TWINS / f"{target}.txt").write_text("\n".join(lines) + "\n")
        print(f"{target}: {len(pairs)} twin functions")


def ranges_sources():
    """(module, address) -> source file credited in config/decomp_ranges.txt."""
    result = {}
    for line in RANGES.read_text().splitlines():
        fields = line.partition("#")[0].split()
        if len(fields) == 4:
            for a in range(int(fields[1], 16), int(fields[2], 16), 4):
                result[fields[0], a] = fields[3]
    return result


# --- C items --------------------------------------------------------------------------------


class Item:
    def __init__(self, path, text, name, kind):
        self.path, self.text, self.name, self.kind = path, text, name, kind


def split_items(path):
    """Top-level items of a C file: functions, objects, types and preprocessor lines."""
    text = path.read_text()
    items, i, n, start = [], 0, len(text), 0
    depth = 0
    while i < n:
        ch = text[i]
        if text.startswith("/*", i):
            i = text.index("*/", i) + 2
            continue
        if text.startswith("//", i):
            i = text.find("\n", i)
            i = n if i < 0 else i
            continue
        if ch in "\"'":
            j = i + 1
            while text[j] != ch:
                j += 2 if text[j] == "\\" else 1
            i = j + 1
            continue
        if depth == 0 and ch == "#" and (i == 0 or text[i - 1] == "\n"):
            j = i
            while True:
                end = text.find("\n", j)
                end = n if end < 0 else end
                if text[end - 1] != "\\":
                    break
                j = end + 1
            items.append(Item(path, text[i:end], None, "pp"))
            i = start = end
            continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                chunk = text[start : i + 1]
                if re.search(r"\)\s*\{", chunk) and not re.match(
                    r"\s*(typedef|struct|enum)", chunk
                ):
                    items.append(Item(path, chunk.strip(), function_name(chunk), "function"))
                    start = i + 1
        elif ch == ";" and depth == 0:
            chunk = text[start : i + 1].strip()
            items.append(Item(path, chunk, object_name(chunk), classify(chunk)))
            start = i + 1
        i += 1
    return items


def strip_comments(text):
    return re.sub(r"/\*.*?\*/|//[^\n]*", " ", text, flags=re.S)


def function_name(chunk):
    head = strip_comments(chunk.split("{", 1)[0])
    return re.findall(r"(\w+)\s*\(", head)[0]


def object_name(chunk):
    head = strip_comments(chunk).split("=", 1)[0]
    if "(" in head and "=" not in strip_comments(chunk):
        return function_name(head + "{")  # prototype
    names = IDENT.findall(head.split("[", 1)[0])
    return names[-1] if names else None


def classify(chunk):
    body = strip_comments(chunk).strip()
    if re.match(r"(typedef|enum|struct|union)\b", body) and "=" not in body.split("{", 1)[0]:
        return "type"
    if "(" in body.split("=", 1)[0] and "=" not in body:
        return "prototype"
    return "object"


ADDRESS_NAME = re.compile(r"\b([A-Z_][A-Z0-9_]*)\s*=\s*(0x8[0-9a-fA-F]{7}u?)\b")
ADDRESS_MACRO = re.compile(r"#define\s+([A-Z_][A-Z0-9_]*)\s+\(?(0x8[0-9a-fA-F]{7}u?)\)?\s*$")


def address_names(files):
    """Enum constants and macros whose value is an address, by name. A name with two
    different values is ambiguous and maps to None."""
    names = {}
    for items in files.values():
        for item in items:
            found = []
            if item.kind == "type":
                found = ADDRESS_NAME.findall(strip_comments(item.text))
            elif item.kind == "pp" and (m := ADDRESS_MACRO.match(item.text)):
                found = [m.groups()]
            for name, value in found:
                names[name] = value if names.get(name, value) == value else None
    return names


def load_items():
    defs = {}
    files = {}
    for path in sorted((ROOT / "src" / "decomp").glob("*.[ch]")):
        items = split_items(path)
        files[path] = items
        for item in items:
            if item.kind in ("function", "object") and item.name:
                defs.setdefault(item.name, item)
    return defs, files


# --- generation -----------------------------------------------------------------------------


def load_twins(target):
    units, amap, himap = [], {}, {}
    path = TWINS / f"{target}.txt"
    if not path.exists():
        return units, amap, himap
    for line in path.read_text().splitlines():
        fields = line.partition("#")[0].split()
        if not fields:
            continue
        if fields[0] == "unit":
            runs = [tuple(int(x, 16) for x in r.split("-")) for r in fields[4:]]
            units.append((int(fields[1], 16), int(fields[2], 16), int(fields[3], 16), runs, {}, {}))
        elif fields[0] == "umap":
            units[-1][4][int(fields[1], 16)] = int(fields[2], 16)
        elif fields[0] == "uhi":
            units[-1][5][int(fields[1], 16)] = int(fields[2], 16)
        elif fields[0] == "map":
            amap[int(fields[1], 16)] = int(fields[2], 16)
        elif fields[0] == "hi":
            himap[int(fields[1], 16)] = int(fields[2], 16)
    return units, amap, himap


def source_entries():
    rows, at_rows = {}, set()
    for path in sorted(SPLICES.glob("*.txt")):
        if path.name.startswith("twins_"):
            continue
        for line in path.read_text().splitlines():
            fields = line.split("#", 1)[0].split(None, 3)
            if len(fields) == 4 and fields[0] == SOURCE:
                addr = int(fields[1], 16)
                if fields[2] == "entry":
                    rows[addr] = fields[3]
                else:
                    at_rows.add(addr)
    return rows, at_rows


def target_splices():
    """Addresses each module already has handwritten splices at (outside the ports)."""
    found = defaultdict(set)
    for path in sorted(SPLICES.glob("*.txt")):
        if path.name.startswith("twins_"):
            continue
        for line in path.read_text().splitlines():
            fields = line.split("#", 1)[0].split(None, 3)
            if len(fields) == 4 and fields[2] in ("entry", "at"):
                found[fields[0]].add(int(fields[1], 16))
    return found


class Port:
    """Clones for one target module."""

    def __init__(self, target, amap, himap, defs):
        self.target, self.amap, self.himap, self.defs = target, amap, himap, defs
        self.names = {}  # address-valued enum constants and macros
        self.cache = {}

    def translate(self, text, local=None):
        """Text with every address literal translated, or None if one has no translation.

        `local` holds a routine's own (address, %hi) translations, which win."""
        text = self.expand(text)
        if text is None:
            return None
        amap, himap = self.amap, self.himap
        if local is not None:
            amap, himap = {**amap, **local[0]}, {**himap, **local[1]}
        failed = False

        def repl(m):
            nonlocal failed
            value = int(m[1], 16)
            if not LAUNCHER_LO <= value < RAM_HI:
                return m[0]
            result = amap.get(value)
            if value & 0xFFFF == 0:
                # Usually a %hi value; it may also be a full address. Translate only when
                # every reading agrees.
                full, hi = result, himap.get(value)
                if hi is not None and full is not None and full != hi:
                    result = None
                elif hi is not None:
                    result = hi
                elif full is not None and full & 0xFFFF:
                    result = None
            if result is not None:
                digits = f"{result:08x}" if m[1].islower() else f"{result:08X}"
                return f"0x{digits}{m[2]}"
            if value < OVERLAY_LO:
                return m[0]  # the resident launcher is shared by every executable
            failed = True
            return m[0]

        text, settled = self.split_pass(text, amap, himap)
        if text is None:
            return None
        parts = re.split(r"(/\*.*?\*/|//[^\n]*)", text, flags=re.S)
        out = []
        for k, part in enumerate(parts):
            failed_before = failed
            translated = LITERAL.sub(repl, part)
            if k % 2:  # a comment: translate what can be, never refuse over it
                failed = failed_before
            out.append(translated)
        if failed:
            return None
        out = "".join(out)
        for key, value in settled.items():
            out = out.replace(key, f"0x{value:08x}")
        return out

    def expand(self, text):
        """Replace address-valued enum constants and macros by their literal value."""
        failed = False

        def repl(m):
            nonlocal failed
            if m[0] not in self.names:
                return m[0]
            if self.names[m[0]] is None:
                failed = True
                return m[0]
            return self.names[m[0]]

        out = IDENT.sub(repl, text)
        return None if failed else out

    def split_pass(self, text, amap, himap):
        """Translate addresses built from a %hi value and a short offset as a pair.

        A register set to a %hi literal and then used as `R(k) + offset` addresses
        hi + offset; translate that address and split it again. Every use of one %hi
        literal must agree on the new %hi value."""
        events = sorted(
            [(m.start(), "set", m) for m in HI_SET.finditer(text)]
            + [(m.start(), "use", m) for m in REG_OFFSET.finditer(text)]
            # A write takes effect at the end of its statement, after the uses inside it.
            + [(statement_end(text, m.end()), "write", m) for m in REG_WRITE.finditer(text)],
            key=lambda e: e[0],
        )
        live, needs, edits = {}, {}, []
        for _, kind, m in events:
            if kind == "set":
                lit = re.search(r"0x(8[0-9a-fA-F]{3}0000)", m[0])
                live[m[1]] = (m.start() + lit.start(), int(lit[1], 16))
            elif kind == "write" and not HI_SET.match(text, m.start()):
                # dest = R(a) + R(b) keeps the %hi base of a live operand (an index added
                # before the low half); any other write ends it.
                add = REG_ADD.match(text, m.start())
                bases = [live[r] for r in add.groups()[1:] if r in live] if add else []
                if len(bases) == 1:
                    live[m[1]] = bases[0]
                else:
                    live.pop(m[1], None)
            elif kind == "use" and m[1] in live:
                at, hi = live[m[1]]
                sign = -1 if m[2] == "-" else 1
                offset = sign * int(m[3], 0)
                full = amap.get((hi + offset) & 0xFFFFFFFF)
                if full is None:
                    return None, {}
                new_hi = (full + 0x8000) & 0xFFFF0000
                if needs.setdefault(at, new_hi) != new_hi:
                    return None, {}
                low = full - new_hi
                edits.append(
                    (
                        m.start(3) - len(m[2]) - (m.start(3) - m.end(2)),
                        m.end(3),
                        f"{'-' if low < 0 else '+'} 0x{abs(low):x}",
                        m,
                    )
                )
        # A %hi literal loaded into a register and not settled by an offset above is
        # translated as a %hi value.
        for m in HI_SET.finditer(text):
            lit = re.search(r"0x(8[0-9a-fA-F]{3}0000)", m[0])
            at = m.start() + lit.start()
            if at not in needs:
                hi = himap.get(int(lit[1], 16))
                if hi is None:
                    return None, {}
                needs[at] = hi
        if not needs:
            return text, {}
        settled, out, last = {}, [], 0
        marks = [(at, at + 10, f"@@HI{n}@@") for n, at in enumerate(sorted(needs))]
        for n, at in enumerate(sorted(needs)):
            settled[f"@@HI{n}@@"] = needs[at]
        pieces = sorted([(s, e, r) for s, e, r in marks] + [(s, e, r) for s, e, r, _ in edits])
        for s, e, r in pieces:
            out.append(text[last:s])
            out.append(r)
            last = e
        out.append(text[last:])
        return "".join(out), settled

    def needs_clone(self, name, stack=()):
        """True if `name` must be cloned (its code, or code it uses, holds addresses)."""
        if name in self.cache:
            return self.cache[name]
        item = self.defs.get(name)
        if item is None or name in stack:
            return False
        self.cache[name] = False  # provisional, for recursion
        body = self.expand(strip_comments(item.text)) or strip_comments(item.text) + " 0x80018000"
        own = any(LAUNCHER_LO <= int(m[1], 16) < RAM_HI for m in LITERAL.finditer(body))
        result = own or any(
            self.needs_clone(ident, (*stack, name))
            for ident in set(IDENT.findall(body))
            if ident != name and ident in self.defs
        )
        if not result and item.path.suffix == ".c" and is_static(item):
            result = True  # a static helper is invisible outside its file
        self.cache[name] = result
        return result

    def clone_name(self, item):
        return f"{item.name}__{item.path.stem}__{self.target}"

    def closure(self, root):
        """Helpers to clone for a root routine, or None if one cannot be translated."""
        seen, order = {root.name: root}, []

        def visit(name):
            item = self.defs.get(name)
            if item is None or name in seen or not self.needs_clone(name):
                return True
            seen[name] = item
            for ident in sorted(set(IDENT.findall(strip_comments(item.text)))):
                if ident != name and not visit(ident):
                    return False
            if self.translate(item.text) is None:
                return False
            order.append(item)
            return True

        idents = sorted(set(IDENT.findall(strip_comments(root.text))))
        if all(visit(i) for i in idents if i != root.name):
            return order
        return None

    def render(self, item, renames, local=None, name=None):
        text = self.translate(item.text, local)
        names = renames if name is None else {**renames, item.name: name}
        head, brace, body = text.partition("{")
        text = IDENT.sub(lambda m: names.get(m[0], m[0]), head) + brace
        text += IDENT.sub(lambda m: renames.get(m[0], m[0]), body)
        if is_static(item) and item.kind == "function":
            text = re.sub(
                r"^((?:\s*/\*.*?\*/)*\s*)static\s+(?:inline\s+)?", r"\1", text, count=1, flags=re.S
            )
        return text


REG_ADD = re.compile(r"set_reg\w*\(c, (\d+), R\((\d+)\) \+ R\((\d+)\)\)")
REG_OFFSET = re.compile(r"R\((\d+)\)\s*([-+])\s*(0x[0-9a-fA-F]{1,4}|\d+)\b")
REG_WRITE = re.compile(r"(?:set_reg\w*\(c, |load_\w+\(c, |R\()(\d+)\)?(?:,|\s*=[^=])")
HI_SET = re.compile(r"(?:set_reg\w*\(c, |R\()(\d+)\)?,? ?=? ?0x8[0-9a-fA-F]{3}0000u?\b")


def statement_end(text, pos):
    end = text.find(";", pos)
    return len(text) if end < 0 else end


def is_static(item):
    return re.match(r"\s*(?:/\*.*?\*/\s*)*static\b", item.text, re.S) is not None


def prototype(text):
    head = text.split("{", 1)[0].strip()
    head = re.sub(r"/\*.*?\*/", "", head, flags=re.S).strip()
    return head + ";"


def generate():
    defs, files = load_items()
    rows, at_rows = source_entries()
    spliced = target_splices()
    outputs = {}
    ranges = []
    for target in TARGETS:
        units, amap, himap = load_twins(target)
        port = Port(target, amap, himap, defs)
        port.names = address_names(files)
        accepted, entries = [], []
        roots = []  # (item, local maps, clone name)
        for src_start, src_end, dst_start, runs, unit_map, unit_hi in units:
            unit_rows = {a: e for a, e in rows.items() if src_start <= a < src_end}
            if src_start not in unit_rows or any(src_start <= a < src_end for a in at_rows):
                continue
            dst_end = dst_start + src_end - src_start
            if any(dst_start <= a < dst_end for a in spliced[target]):
                continue
            calls, unit_roots = {}, []
            local = (unit_map, unit_hi)
            for addr, call in unit_rows.items():
                name = re.match(r"(\w+)\(", call)[1]
                root = defs.get(name)
                if root is None:
                    break
                dst = addr - src_start + dst_start
                order = port.closure(root)
                text = port.translate(call, local)
                if order is None or text is None or port.translate(root.text, local) is None:
                    break
                clone = f"{name}__{target}_{dst:08X}"
                text = re.sub(rf"\b{name}\(", f"{clone}(", text, count=1)
                calls[dst] = (text, order)
                unit_roots.append((root, local, clone))
            else:
                accepted.append((dst_start, runs))
                entries.extend(calls.items())
                roots.extend(unit_roots)
        clones = {}
        for _, (_, order) in entries:
            for item in order:
                clones[item.name] = item
        renames = {name: port.clone_name(item) for name, item in clones.items()}
        by_file, roots_by_file = defaultdict(list), defaultdict(list)
        for item in clones.values():
            by_file[item.path].append(item)
        for root in roots:
            roots_by_file[root[0].path].append(root)
            by_file.setdefault(root[0].path, [])
        header = OUT / f"{target}.h"
        guard = f"NC_DECOMP_TWINS_{target.upper()}_H"
        decls = [
            prototype(port.render(item, renames))
            for path in sorted(by_file)
            for item in by_file[path]
            if item.kind == "function"
        ] + [
            prototype(port.render(item, renames, local, name))
            for path in sorted(roots_by_file)
            for item, local, name in sorted(roots_by_file[path], key=lambda r: r[2])
        ]
        needed = set()
        for path in by_file:
            if path.suffix == ".h":
                needed.add(f'#include "decomp/{path.name}"')
            else:
                needed.update(
                    it.text
                    for it in files[path]
                    if it.kind == "pp" and it.text.startswith("#include")
                )
        outputs[header] = "\n".join(
            [
                f"/* Generated by tools/port_twins.py: {SOURCE} routines ported to {target}. */",
                f"#ifndef {guard}",
                f"#define {guard}",
                "",
                '#include "port/recomp.h"',
                *sorted(needed),
                "",
                *decls,
                "",
                "#endif",
                "",
            ]
        )
        for path, items in sorted(by_file.items()):
            original = files[path]
            names = {it.name for it in items}
            body = [
                f"/* Generated by tools/port_twins.py from src/decomp/{path.name}: {SOURCE}",
                f" * routines with every address translated for {target}. Edit the original and",
                " * rerun. */",
            ]
            if path.suffix == ".h":
                body.append(f'#include "decomp/{path.name}"')
            body.append(f'#include "decomp/twins/{target}.h"')
            for it in original:
                if it.kind == "pp" and path.suffix == ".c" and it.text.startswith("#include"):
                    body.append(it.text)
                elif (
                    it.kind in ("pp", "type")
                    and path.suffix == ".c"
                    and not it.text.startswith("#include")
                ):
                    body.append(it.text)
                elif it.name in names:
                    body.append(port.render(it, renames))
            for it, local, name in sorted(roots_by_file[path], key=lambda r: r[2]):
                body.append(port.render(it, renames, local, name))
            outputs[OUT / f"{target}_{path.stem}.c"] = "\n\n".join(body) + "\n"
        splice = [
            f"# Generated by tools/port_twins.py: {SOURCE} routines ported to {target}.",
            "",
            f"include decomp/twins/{target}.h",
            "",
        ]
        for addr, (call, _) in sorted(entries):
            splice.append(f"{target}  {addr:08X}  entry  {call}")
        outputs[SPLICES / f"twins_{target}.txt"] = "\n".join(splice) + "\n"
        for _dst, runs in sorted(accepted):
            for start, end in runs:
                ranges.append(f"{target:<12} {start:08X}    {end:08X}         twins/{target}")
    text = RANGES.read_text()
    head = text.split(RANGES_MARK, 1)[0].rstrip("\n")
    outputs[RANGES] = "\n".join([head, "", RANGES_MARK, *ranges]) + "\n"
    return outputs


def clang_format(path, text):
    """Format generated C like the rest of src (pinned clang-format, see requirements.txt)."""
    tool = ROOT / ".venv" / "bin" / "clang-format"
    tool = str(tool) if tool.exists() else "clang-format"
    result = subprocess.run(
        [tool, f"--assume-filename={path}"],
        input=text,
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    return result.stdout


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--discover", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    sys.path.insert(0, str(ROOT / "tools"))
    if args.discover:
        discover()
    outputs = generate()
    for path in outputs:
        if path.suffix in (".c", ".h"):
            outputs[path] = clang_format(path, outputs[path])
    stale = []
    for path, text in outputs.items():
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    if args.check:
        known = {p for p in outputs}
        stale += [p.relative_to(ROOT) for p in OUT.glob("*") if p not in known]
        if stale:
            print("Out of date (run tools/port_twins.py):", *stale, sep="\n  ")
            return 1
    else:
        for path in OUT.glob("*"):
            if path not in outputs:
                path.unlink()
    return 0


if __name__ == "__main__":
    sys.exit(main())
